"""#26 VC export helpers — structure & status layer tests.

Bitstring decoding is pinned with a fixed cross-language vector: the string
below was produced by the Node signer stack (zlib gzipSync + base64url) and
is asserted byte-for-byte here — apps/api-sg/src/vc-status-list.test.ts pins
the same vector, guaranteeing signer(Node) → verifier(Python) interop.
"""

from __future__ import annotations

import gzip
import base64
import json

import pytest

from jiaozi_gdid import (
    VcExportError,
    build_status_payload,
    check_bitstring_entry,
    check_vc_status,
    credential_status_entries,
    decode_status_list_bitstring,
    fetch_vc,
    generate_ed25519_keypair,
    sign_status_payload,
    status_list_bit,
    validate_vc_structure,
)

CORE = "https://core.test"

# bits {0, 1, 4000, 131071} set in a 131,072-bit (16KB) list — generated by
# the Node encoder; same constant lives in vc-status-list.test.ts
FIXED_VECTOR = (
    "uH4sIAAAAAAAACu3OMQEAAAQAMJqLJppfAYctwTr4pq4DAAAAAAAAAAAAAAAAAAAAbDkt82tcAEAAAA"
)
FIXED_VECTOR_SET_BITS = [0, 1, 4000, 131071]


def encode_bitstring(bits: bytes) -> str:
    """Local reference encoder (mirrors the Node side) for roundtrip tests."""
    return "u" + base64.urlsafe_b64encode(gzip.compress(bits, mtime=0)).decode().rstrip("=")


def make_bits(set_indexes: list[int], size_bytes: int = 16384) -> bytes:
    buf = bytearray(size_bytes)
    for i in set_indexes:
        buf[i >> 3] |= 0x80 >> (i & 7)
    return bytes(buf)


class FakeResponse:
    def __init__(self, body, status_code: int = 200):
        self._body = body
        self.status_code = status_code

    def json(self):
        return json.loads(json.dumps(self._body))


class FakeClient:
    """Maps URL → response; records requests."""

    def __init__(self, routes: dict):
        self.routes = routes
        self.requested: list[str] = []

    def get(self, url: str) -> FakeResponse:
        self.requested.append(url)
        if url not in self.routes:
            return FakeResponse({"error": "not_found"}, 404)
        body = self.routes[url]
        if isinstance(body, FakeResponse):
            return body
        return FakeResponse(body)


